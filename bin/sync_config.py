"""
Sync LogstashAgent config for the *legacy* local start path
(``bin/start_logstashui.sh|bat`` when ``simulation.mode: host``).

Writes an **embedded** agent role with supervisor ``simulation_mode: host``
so Logstash is Popen'd against package paths. This is **not** an enrolled
``mode: simulate`` / ``ls-simulate@N`` instance.

Prefer enrolling a **Simulate** policy agent for multi-instance, isolated
simulation (see docs: simulate agents / formerly host mode).
"""
import os
import sys
from pathlib import Path

import yaml

try:
    # Check for logstashui.yml first, fallback to logstashui.example.yml
    if os.path.exists('src/logstashui/logstashui.yml'):
        config_file = 'src/logstashui/logstashui.yml'
    elif os.path.exists('src/logstashui/logstashui.example.yml'):
        config_file = 'src/logstashui/logstashui.example.yml'
    else:
        raise FileNotFoundError("No config file found in src/logstashui/")

    with open(config_file, 'r', encoding='utf-8') as f:
        config = yaml.safe_load(f) or {}

    raw = config.get('simulation', {}).get('logstash_agent', {}) or {}
    agent_config = dict(raw)

    # Local start-script agent is always FastAPI + supervisor (not enrolled --run).
    # Keep package Logstash path keys from yml; force vocabulary for supervisor host path.
    agent_config['mode'] = 'embedded'
    agent_config['simulation_mode'] = 'host'
    agent_config.setdefault('port', 9501)
    # Drop enrolled-simulate-only keys that would confuse local tooling
    for key in (
        'instance_id',
        'agent_api_port',
        'logstash_api_port',
        'logstash_unit',
        'agent_unit',
        'keystore_env_file',
    ):
        agent_config.pop(key, None)

    agent_config_dir = Path('LogstashAgent/src/logstashagent')
    if not agent_config_dir.exists():
        print(f"Warning: {agent_config_dir} does not exist. Agent may not be cloned yet.")
        sys.exit(1)

    agent_config_path = agent_config_dir / 'config' / 'logstashagent.yml'
    agent_config_path.parent.mkdir(parents=True, exist_ok=True)
    with open(agent_config_path, 'w', encoding='utf-8') as f:
        f.write(
            "# Generated by bin/sync_config.py for legacy simulation.mode: host start path.\n"
            "# mode=embedded + simulation_mode=host → supervisor manages package Logstash.\n"
            "# Prefer: enroll a Simulate policy (lsagent-simulate@N / ls-simulate@N).\n"
        )
        yaml.dump(agent_config, f, default_flow_style=False, sort_keys=False)

    print(f"Config synced successfully to {agent_config_path}")
    print(
        "Legacy local-host path: mode=embedded, simulation_mode=host "
        "(supervisor). Prefer enrolled Simulate agents for production-quality sim."
    )
    sys.exit(0)
except Exception as e:
    print(f"Warning: Could not sync config: {e}")
    sys.exit(1)
